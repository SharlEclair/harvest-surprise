"""Data-quality catalogue: every raw table, counted rather than assumed.

The pitwall repository's habit is that bad data is detected, coded, counted and
quarantined, never dropped silently. This applies the same idea to every raw pull
in this study and writes a human-readable catalogue.

Checks per table:
  rows, date coverage, duplicate keys, missingness on identity columns,
  sentinel values (-9999, 0), and physically impossible values.

Output: docs/DQ.md, data/processed/dq_summary.csv
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "data" / "processed"
DOCS = ROOT / "docs"

SENTINEL = -9999.0


def check(name: str, df: pd.DataFrame, keys: list[str], date_col: str | None,
          value_cols: list[str] | None = None) -> dict:
    rec = {"table": name, "rows": len(df), "cols": df.shape[1]}
    if date_col and date_col in df:
        d = pd.to_datetime(df[date_col], errors="coerce")
        rec["date_min"] = d.min().date() if d.notna().any() else None
        rec["date_max"] = d.max().date() if d.notna().any() else None
        rec["date_missing"] = int(d.isna().sum())
    if keys and all(k in df for k in keys):
        rec["dup_keys"] = int(df.duplicated(keys).sum())
    if keys:
        rec["null_keys"] = int(df[[k for k in keys if k in df]].isna().any(axis=1).sum())
    for col in value_cols or []:
        if col not in df:
            continue
        v = pd.to_numeric(df[col], errors="coerce")
        rec[f"{col}_null"] = int(v.isna().sum())
        rec[f"{col}_sentinel"] = int((v == SENTINEL).sum())
        rec[f"{col}_nonpositive"] = int((v <= 0).sum())
    return rec


def main() -> int:
    OUT.mkdir(exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    if not RAW.exists():
        raise SystemExit("no data/raw")

    jobs = [
        ("nass_yield", ["state_alpha", "year", "reference_period_desc"], None, ["value"]),
        ("nass_area_harvested", ["state_alpha", "year"], None, ["value"]),
        ("nass_area_planted", ["state_alpha", "year"], None, ["value"]),
        ("nass_condition", ["state_alpha", "week_ending", "short_desc"], "week_ending", ["value"]),
        ("nass_rice_county", ["year", "county_name"], None, ["acres"]),
        ("wasde_corn", ["ReleaseDate", "MarketYear", "Attribute", "Unit"], "ReleaseDate", ["Value"]),
        ("prices_daily", ["date", "ticker"], "date", ["close"]),
        ("weather_state_year", ["state_alpha", "year"], None,
         ["asof_gdd", "asof_precip", "asof_tmax_jul"]),
        ("cdec_reservoirs", ["station", "date"], "date", ["elevation_ft", "storage_af"]),
        ("caiso_dam", ["hub", "timestamp"], "timestamp", ["lmp"]),
    ]

    rows = []
    for name, keys, date_col, vals in jobs:
        f = RAW / f"{name}.csv"
        if not f.exists():
            print(f"{name}: not present, skipped")
            continue
        df = pd.read_csv(f, low_memory=False)
        rec = check(name, df, keys, date_col, vals)
        rows.append(rec)
        print(f"{name:22s} rows={rec['rows']:7d} dups={rec.get('dup_keys', '-')} "
              f"nulls={rec.get('null_keys', '-')}")

    if not rows:
        raise SystemExit("nothing to catalogue")
    summ = pd.DataFrame(rows)
    summ.to_csv(OUT / "dq_summary.csv", index=False)

    lines = ["# Data-quality catalogue", "",
             "Generated by `analysis/dq_catalogue.py`. Counts are over the raw pull as it",
             "sits on disk; nothing is repaired here, only counted.", ""]
    for _, r in summ.iterrows():
        lines.append(f"## {r.table}")
        lines.append("")
        bits = [f"{r.rows:,} rows"]
        if "date_min" in r and pd.notna(r.date_min):
            bits.append(f"{r.date_min} to {r.date_max}")
        if "dup_keys" in r and pd.notna(r.dup_keys):
            bits.append(f"{int(r.dup_keys)} duplicate key rows")
        if "null_keys" in r and pd.notna(r.null_keys):
            bits.append(f"{int(r.null_keys)} rows with a null key")
        lines.append("- " + "; ".join(bits))
        vals = {c: r[c] for c in r.index
                if c.endswith(("_null", "_sentinel", "_nonpositive")) and pd.notna(r[c]) and r[c] > 0}
        if vals:
            lines.append("- positive problem counts: " +
                         ", ".join(f"`{k}`={int(v)}" for k, v in vals.items()))
        else:
            lines.append("- no sentinel, null or non-positive values in the checked columns")
        lines.append("")
    (DOCS / "DQ.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {DOCS/'DQ.md'} and {OUT/'dq_summary.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
